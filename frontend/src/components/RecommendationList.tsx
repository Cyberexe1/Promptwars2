import {
  CATEGORY_LABELS,
  CATEGORY_ORDER,
  CONFIDENCE_LABELS,
  COST_LABELS,
  EFFORT_LABELS,
  formatTimestamp,
} from '../labels';
import type { Recommendation, RecommendationsResponse } from '../types';

interface RecommendationListProps {
  plan: RecommendationsResponse;
}

function RecommendationCard({ item }: { item: Recommendation }) {
  return (
    <li className="recommendation">
      <h4>{item.title}</h4>

      <p className="recommendation-action">{item.action}</p>

      <dl className="recommendation-detail">
        <dt>Why it helps</dt>
        <dd>{item.why}</dd>

        <dt>Effect on your household</dt>
        <dd>{item.personalImpact}</dd>

        <dt>Effect on your community</dt>
        <dd>{item.communityImpact}</dd>
      </dl>

      <ul className="tag-list">
        <li className="tag">{COST_LABELS[item.cost]}</li>
        <li className="tag">{EFFORT_LABELS[item.effort]}</li>
        <li className="tag">Evidence: {CONFIDENCE_LABELS[item.confidence]}</li>
      </ul>
    </li>
  );
}

/**
 * The generated plan, grouped by category.
 *
 * Provenance is shown explicitly: the reader can see whether wording came from
 * the rules engine or the model, and that impact figures are estimates.
 */
export function RecommendationList({ plan }: RecommendationListProps) {
  const grouped = CATEGORY_ORDER.map((category) => ({
    category,
    items: plan.recommendations.filter((item) => item.category === category),
  })).filter((group) => group.items.length > 0);

  return (
    <section className="card" aria-labelledby="plan-heading">
      <h2 id="plan-heading">Your clean-air plan</h2>

      <p className="plan-summary">{plan.summary}</p>

      {plan.risk.escalatedForSensitivity && (
        <p className="alert alert-info" role="note">
          Official air quality is rated <strong>{plan.risk.label}</strong>.
          Because someone in your household is more affected by particle
          pollution, this plan follows the next stricter level of precaution.
        </p>
      )}

      {plan.airQuality.stale && (
        <p className="alert alert-warning" role="status">
          The underlying reading is over three hours old, so treat this plan as
          general precaution rather than a live assessment.
        </p>
      )}

      {grouped.map((group) => (
        <div key={group.category} className="plan-group">
          <h3>{CATEGORY_LABELS[group.category]}</h3>
          <ul className="recommendation-list">
            {group.items.map((item) => (
              <RecommendationCard key={item.id} item={item} />
            ))}
          </ul>
        </div>
      ))}

      <footer className="plan-footer">
        <p className="provenance">
          Based on a reading observed{' '}
          {formatTimestamp(plan.airQuality.current.observedAt)} from{' '}
          <a
            href={plan.airQuality.source.url}
            target="_blank"
            rel="noreferrer noopener"
          >
            {plan.airQuality.source.name}
          </a>
          . Wording generated by{' '}
          {plan.generatedBy === 'bedrock'
            ? 'Amazon Bedrock, from a fixed set of reviewed recommendations'
            : 'the built-in rules engine'}
          .
        </p>
        <p className="disclaimer">{plan.disclaimer}</p>
      </footer>
    </section>
  );
}
