<#
    End-to-end check against the deployed stack.

    Exercises the full browser flow: pick up a CSRF token, create an account,
    request a plan, and confirm the protections hold.
#>
$ErrorActionPreference = 'Continue'
$api = 'https://yzjmcnk4t4.us-east-1.awsapprunner.com'
$site = 'https://d1lae1x52oxefj.cloudfront.net'

function Show($label, $value) { Write-Host ("{0,-34} {1}" -f $label, $value) }

$jar = Join-Path $env:TEMP 'sw-live-cookies.txt'
$signupFile = Join-Path $env:TEMP 'sw-live-signup.json'
$planFile = Join-Path $env:TEMP 'sw-live-plan.json'
Remove-Item $jar -ErrorAction SilentlyContinue

# 1. Pick up a CSRF token the way the page does, via the session check.
curl.exe -s -o NUL -c $jar "$api/api/auth/me" 2>&1 | Out-Null
$csrfLine = Get-Content $jar -ErrorAction SilentlyContinue | Select-String 'smogwise_csrf'
$csrf = if ($csrfLine) { ($csrfLine.Line -split "`t")[-1].Trim() } else { $null }
Show 'csrf token issued' $(if ($csrf) { 'yes' } else { 'NO' })

# 2. A state-changing request without the header must be refused.
('{"email":"nocsrf' + (Get-Random) + '@example.com","password":"correct horse battery staple"}') |
    Set-Content $signupFile -Encoding ascii -NoNewline
$noToken = curl.exe -s -o NUL -w '%{http_code}' -b $jar -X POST "$api/api/auth/signup" `
    -H 'content-type: application/json' --data-binary "@$signupFile" 2>&1
Show 'signup without csrf header' "$noToken (expect 403)"

# 3. With the header it should succeed.
$email = "live$(Get-Random)@example.com"
('{"email":"' + $email + '","password":"correct horse battery staple"}') |
    Set-Content $signupFile -Encoding ascii -NoNewline
$signup = curl.exe -s -o NUL -w '%{http_code}' -b $jar -c $jar -X POST "$api/api/auth/signup" `
    -H 'content-type: application/json' -H "x-csrf-token: $csrf" `
    --data-binary "@$signupFile" 2>&1
Show 'signup with csrf header' "$signup (expect 201)"

# 4. Authenticated plan request.
'{"location":{"name":"Delhi","latitude":28.65,"longitude":77.23},"profile":{"ageGroups":["child","adult"],"sensitive":true,"commuteMethod":"motorbike","outdoorMinutes":90,"cookingFuel":"biomass","purifier":false,"budget":"low"}}' |
    Set-Content $planFile -Encoding ascii -NoNewline

$raw = curl.exe -s -b $jar -X POST "$api/api/recommendations" `
    -H 'content-type: application/json' -H "x-csrf-token: $csrf" `
    --data-binary "@$planFile" 2>&1 | Out-String

try {
    $plan = $raw | ConvertFrom-Json
    Show 'plan generated by' $plan.generatedBy
    Show 'recommendations' $plan.recommendations.Count
    Show 'official band' $plan.risk.level
    Show 'effective band' $plan.risk.effectiveLevel
    Show 'no percentage claims' (-not ($raw -match '\d+\s?%'))
}
catch { Show 'plan' ('unparseable: ' + $raw.Trim().Substring(0, 120)) }

# 5. Code-split chunks must be reachable through CloudFront.
Write-Host ''
$html = curl.exe -s $site 2>&1 | Out-String
$chunks = [regex]::Matches($html, '/assets/[A-Za-z0-9._-]+\.js') | ForEach-Object { $_.Value } | Sort-Object -Unique
Show 'chunks referenced by index' $chunks.Count
foreach ($chunk in $chunks) {
    $code = curl.exe -s -o NUL -w '%{http_code}' "$site$chunk" 2>&1
    Show ('  ' + $chunk.Replace('/assets/', '')) $code
}

Remove-Item $jar, $signupFile, $planFile -ErrorAction SilentlyContinue
