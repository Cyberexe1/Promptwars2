# Focused check of signup and the authenticated plan endpoint on the deployed
# service. Uses a temp file for the JSON body: PowerShell mangles multi-line
# JSON passed inline to curl.
$ErrorActionPreference = 'Continue'
$api = 'https://yzjmcnk4t4.us-east-1.awsapprunner.com'

function Show($label, $value) { Write-Host ("{0,-28} {1}" -f $label, $value) }

$email = "live$(Get-Random)@example.com"
$bodyFile = Join-Path $env:TEMP 'sw-signup.json'
$planFile = Join-Path $env:TEMP 'sw-plan.json'
$cookieJar = Join-Path $env:TEMP 'sw-cookies.txt'
Remove-Item $cookieJar -ErrorAction SilentlyContinue

# Compact, single-line JSON written as a file.
(@{ email = $email; password = 'correct horse battery staple' } | ConvertTo-Json -Compress) |
    Set-Content $bodyFile -Encoding ascii -NoNewline

Show 'email' $email
Write-Host ''
Write-Host 'signup response:'
$response = curl.exe -s -w "`nHTTP %{http_code}" -c $cookieJar -X POST "$api/api/auth/signup" `
    -H 'content-type: application/json' --data-binary "@$bodyFile" 2>&1
$response | ForEach-Object { Write-Host ('  ' + $_) }

Write-Host ''
$hasCookie = (Get-Content $cookieJar -ErrorAction SilentlyContinue | Select-String 'smogwise_session')
Show 'session cookie' $(if ($hasCookie) { 'stored' } else { 'none' })

if ($hasCookie) {
    (@{
        location = @{ name = 'Delhi'; latitude = 28.65; longitude = 77.23 }
        profile  = @{
            ageGroups = @('child', 'adult'); sensitive = $true
            commuteMethod = 'motorbike'; outdoorMinutes = 90
            cookingFuel = 'biomass'; purifier = $false; budget = 'low'
        }
    } | ConvertTo-Json -Depth 6 -Compress) | Set-Content $planFile -Encoding ascii -NoNewline

    Write-Host ''
    Write-Host 'plan request:'
    $planJson = curl.exe -s -b $cookieJar -X POST "$api/api/recommendations" `
        -H 'content-type: application/json' --data-binary "@$planFile" 2>&1 | Out-String

    try {
        $plan = $planJson | ConvertFrom-Json
        Show '  recommendations' $plan.recommendations.Count
        Show '  generated by' $plan.generatedBy
        Show '  official band' $plan.risk.level
        Show '  effective band' $plan.risk.effectiveLevel
        Show '  escalated' $plan.risk.escalatedForSensitivity
        Write-Host ''
        Write-Host '  plan items:'
        $plan.recommendations | ForEach-Object { Write-Host ("    - " + $_.id) }
    }
    catch {
        Write-Host ('  unparseable: ' + $planJson.Trim())
    }
}

Remove-Item $bodyFile, $planFile, $cookieJar -ErrorAction SilentlyContinue
