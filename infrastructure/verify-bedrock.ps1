# Confirms the live service produces model-written wording, and that the
# safety guarantees still hold: the model may only reword the entries the
# rules engine chose, never add or relabel one.
#
# Goes through the site origin, the way the page does. This used to call App
# Runner directly with no CSRF token, which the API now refuses, so the script
# reported an empty plan instead of a result.
$ErrorActionPreference = 'Continue'
$api = 'https://d1lae1x52oxefj.cloudfront.net'

$jar = Join-Path $env:TEMP 'vb-cookies.txt'
$signupFile = Join-Path $env:TEMP 'vb-signup.json'
$planFile = Join-Path $env:TEMP 'vb-plan.json'
Remove-Item $jar -ErrorAction SilentlyContinue

('{"email":"verify' + (Get-Random) + '@example.com","password":"correct horse battery staple"}') |
    Set-Content $signupFile -Encoding ascii -NoNewline
'{"location":{"name":"Delhi","latitude":28.65,"longitude":77.23},"profile":{"ageGroups":["child","adult"],"sensitive":true,"commuteMethod":"motorbike","outdoorMinutes":90,"cookingFuel":"biomass","purifier":false,"budget":"low"}}' |
    Set-Content $planFile -Encoding ascii -NoNewline

# The API issues a CSRF cookie on first contact; the header must echo it.
curl.exe -s -o NUL -c $jar "$api/api/auth/me" 2>&1 | Out-Null
$token = (Get-Content $jar | Where-Object { $_ -match 'smogwise_csrf' } |
        ForEach-Object { ($_ -split "`t")[-1] } | Select-Object -First 1)
if (-not $token) { Write-Host 'no CSRF token was issued'; exit 1 }

$signup = (curl.exe -s -b $jar -c $jar -o NUL -w '%{http_code}' -X POST "$api/api/auth/signup" `
        -H 'content-type: application/json' -H "x-csrf-token: $token" -H "Origin: $api" `
        --data-binary "@$signupFile" 2>&1 | Out-String).Trim()
if ($signup -ne '201') { Write-Host "signup returned $signup, expected 201"; exit 1 }

$raw = curl.exe -s -b $jar -X POST "$api/api/recommendations" `
    -H 'content-type: application/json' -H "x-csrf-token: $token" -H "Origin: $api" `
    --data-binary "@$planFile" 2>&1 | Out-String

try { $plan = $raw | ConvertFrom-Json }
catch { Write-Host 'unparseable response:'; Write-Host $raw.Trim(); exit 1 }
if (-not $plan.recommendations) { Write-Host 'no plan came back:'; Write-Host $raw.Trim(); exit 1 }

Write-Host ("generated by     : " + $plan.generatedBy)
Write-Host ("recommendations  : " + $plan.recommendations.Count)
Write-Host ("official band    : " + $plan.risk.level)
Write-Host ("effective band   : " + $plan.risk.effectiveLevel)
Write-Host ''
Write-Host 'summary:'
Write-Host ('  ' + $plan.summary)
Write-Host ''
Write-Host 'first recommendation as written by the model:'
Write-Host ('  title  : ' + $plan.recommendations[0].title)
Write-Host ('  action : ' + $plan.recommendations[0].action)
Write-Host ('  impact : ' + $plan.recommendations[0].personalImpact)
Write-Host ''

# Safety invariants that must survive model involvement.
$ids = $plan.recommendations | ForEach-Object { $_.id }
Write-Host 'safety checks:'
Write-Host ('  ids are known catalogue entries : ' + (($ids | Where-Object { $_ -match '^[a-z0-9-]+$' }).Count -eq $ids.Count))
Write-Host ('  no duplicate ids               : ' + (($ids | Select-Object -Unique).Count -eq $ids.Count))
Write-Host ('  exercise paused at this band   : ' + ($ids -contains 'pause-outdoor-exercise'))
Write-Host ('  no window-opening advice       : ' + (-not ($ids -contains 'ventilate-at-cleanest-hours')))
Write-Host ('  no percentage claims           : ' + (-not ($raw -match '\d+\s?%')))
Write-Host ('  disclaimer present             : ' + ($plan.disclaimer -match 'not medical advice'))

Remove-Item $jar, $signupFile, $planFile -ErrorAction SilentlyContinue
